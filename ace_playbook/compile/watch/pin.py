"""The `model_pin` rule: a model id the deprecations page says is deprecated or retired, and that the inventory pins.

The diff is generated by code from the matched inventory lines: the pinned id is replaced by the successor, and nothing else changes. It is
written only when the successor is itself a model id (`claude-...`, nothing else), every line is whole (not cut at 300 characters, no U+FFFD,
the target file was not truncated at 100 matching lines or skipped as too large); otherwise the row becomes a `lead` with no diff, titled
"retirement with no successor named". A model whose table says Active or Legacy, or whose retirement is "Not sooner than ...", is not
retiring. Hunk line numbers are `grep -n` numbers. `state` and `pinned` serve `scan`'s "trigger vanished" test.
"""

from __future__ import annotations

import re

from .records import record, sh

SAFE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:-]{2,79}")
MODEL_ID = re.compile(r"claude-[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?")
NONE_WORDS = ("", "n/a", "na", "-", "none", "tbd", "to be announced")
GONE = re.compile(r"(?:deprecated|retired)\b", re.I)                          # a model whose table says Active or Legacy is not retiring
MAX_LINE = 300
TITLE = re.compile(r"Replace (\S+) with \S+ in |retirement with no successor named: (\S+) \(")


def boundary(token: str) -> re.Pattern:
    return re.compile(r"(?<![\w.@-])" + re.escape(token) + r"(?![\w@-]|\.\w)")


def _real(v: object) -> bool:
    """A date or a name, not N/A, not "to be announced" and not the tentative "Not sooner than ..." that an Active model carries."""
    return isinstance(v, str) and v.strip().lower() not in NONE_WORDS and not v.strip().lower().startswith("not sooner")


def state(results: list[dict]) -> dict[str, dict]:
    """`{model id: {res, row, deprecated, retires, successor, state, retiring}}`, the rows of every deprecations table merged per id."""
    merged: dict = {}
    for res in (r for r in results if r["kind"] == "deprecations"):
        for row in res["data"]:
            m = merged.setdefault(row["model_id"], {"res": res, "had": False, **{k: None for k in ("deprecated", "retires", "successor", "row", "state")}})
            for k in ("deprecated", "retires", "successor", "state"):
                m[k] = m[k] or row.get(k)
            if m["row"] is None or (row["successor"] and not m["had"]):
                m["row"], m["had"], m["res"] = row["row"], bool(row["successor"]), res
    for m in merged.values():
        gone = bool(GONE.match((m["state"] or "").strip()))                     # "Deprecated", "Retired", "Deprecated (legacy)"
        m["retiring"] = (m["state"] is None or gone) and (_real(m["deprecated"]) or _real(m["retires"]) or gone)
    return merged


def pinned(inv: dict, key: str, mid: str) -> bool:
    """True when some inventory line of target `key` still names `mid`."""
    rx = boundary(mid)
    return any(isinstance(ln, list) and len(ln) == 2 and rx.search(str(ln[1]))
               for f in inv.get("targets", {}).get(key, {}).get("files", {}).values() for ln in f.get("lines", []))


def model_of(rec: dict) -> str | None:
    """The model id a model_pin proposal or a retirement lead is about (read back from its code-made title)."""
    m = TITLE.match(rec.get("title", "")) if isinstance(rec.get("title"), str) else None
    return (m.group(1) or m.group(2)) if m else None


def _lines(inv: dict, rx: re.Pattern) -> dict[str, dict[str, list]]:
    out: dict = {}
    for key, t in inv.get("targets", {}).items():
        for path, f in t.get("files", {}).items():
            hit = [ln for ln in f.get("lines", []) if isinstance(ln, list) and len(ln) == 2 and rx.search(str(ln[1]))]
            if hit:
                out.setdefault(key, {})[path] = hit
    return out


def _diff(files: dict, rx: re.Pattern, new: str) -> str:
    out = []
    for path, lines in sorted(files.items()):
        out += [f"--- a/{path}", f"+++ b/{path}"]
        for n, text in lines:
            out += [f"@@ -{n},1 +{n},1 @@", f"-{text}", f"+{rx.sub(lambda m: new, text)}"]
    return "\n".join(out) + "\n"


def model_pin(inv: dict, results: list[dict], now: str) -> list[dict]:
    out = []
    for mid, m in sorted(state(results).items()):
        if not SAFE.fullmatch(mid) or not m["retiring"]:
            continue
        rx, new = boundary(mid), m["successor"] if _real(m["successor"]) and MODEL_ID.fullmatch(m["successor"]) and SAFE.fullmatch(m["successor"]) else None
        ev = {"url": m["res"]["url"], "sha256": m["res"]["sha256"], "quote": m["row"], "tier": m["res"]["tier"]}
        for key, files in sorted(_lines(inv, rx).items()):
            verify = f'grep -n "{mid}" ' + " ".join(sh(p) for p in sorted(files))
            cut = any(f.get("truncated") or f.get("too_large") for f in inv["targets"][key]["files"].values())
            whole = new and new != mid and not cut and all(len(str(t)) < MAX_LINE and "�" not in str(t) for ls in files.values() for _, t in ls)
            if whole:
                out.append(record("model_pin", f"Replace {mid} with {new} in {key}", ev, [key], key, _diff(files, rx, new), verify, now))
            else:
                out.append(record("lead", f"retirement with no successor named: {mid} ({key})", ev, [key], key, None, verify, now))
    return out
