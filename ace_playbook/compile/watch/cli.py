"""`compile watch scan|status|queue` (docs/design/compiler.md 8.x "Watch (as built)"): the watcher PROPOSES; nothing here applies a change.

This module is light on purpose (`__main__` imports it to register the verb): the network-using `scan` (and through it `fetch` and
`inventory`) loads only when a scan runs. `queue` is TTY only, like `label --queue`: oldest first, 1 accept / 2 dismiss (a note is
required) / 3 later / q quit; each key appends one decision row and nothing else. Every string that came from the web is cleaned of
control characters before it is printed.
"""

from __future__ import annotations

import os
import sys
from typing import Callable

from .. import status as status_mod
from ... import ttyio
from ...canon import now_iso
from ...config import Config
from . import fsio, store, summary

KEYS = {"1": "accepted", "2": "dismissed", "3": "later", "q": "quit"}
CONTROL, TRIES, DIFF_LINES = "1 accept / 2 dismiss / 3 later / q quit", 3, 40


def _ask(prompt: str) -> str:
    return ttyio.ask(prompt).strip()


def _need_tty(what: str) -> bool:
    if sys.stdin.isatty():
        return True
    print(f"error: {what} needs an interactive terminal (stdin is not a TTY)", file=sys.stderr)
    return False


def add_parser(sub) -> None:
    """Register `watch` (with scan, status and queue) on the CLI's subparsers."""
    p = sub.add_parser("watch", help="the configuration watcher: proposes changes, applies nothing (scan | status | queue)")
    w = p.add_subparsers(dest="watch_cmd", required=True)
    sc = w.add_parser("scan", help="fetch the sources that are due, rebuild the inventory, match, store (the one network-using verb)")
    sc.add_argument("--tier", choices=("0", "1", "all"), default="all", help="only sources of this tier (default all)")
    sc.add_argument("--dry-run", action="store_true", help="fetch and match, write nothing")
    sc.add_argument("--force", action="store_true", help="ignore the daily and weekly cadence")
    w.add_parser("status", help="open proposals, leads, oldest, last scan (read-only)")
    q = w.add_parser("queue", help="TTY only: review open proposals, oldest first, one key each")
    q.add_argument("--limit", type=int, default=50, help="how many cards (default 50)")
    p.set_defaults(run=lambda c, a: run(c, a, _ask, _need_tty))


def _card(p: dict, n: int, total: int) -> None:
    c = store.clean
    ev = p["evidence"][0]
    print(f"\n[{n}/{total}] {c(p['id'])}  {c(p['class'])}  created {c(p['created'])}  expires {c(p['expires'])}\n  title:    {c(p['title'])}\n"
          f"  evidence: tier {c(ev['tier'])}  {c(ev['url'], 200)}\n  quote (untrusted text from the web): {c(ev['quote'], 400)}\n"
          f"  hits:     {c(', '.join(map(str, p['inventory_hits'])) or 'none', 200)}\n  verify:   {c(p['verify'], 300)}\n  keys:     {CONTROL}")
    diff = p["change"]["diff"]
    if diff:
        shown = diff.splitlines()
        print("  diff (generated by code from a template; nothing is applied):")
        print("\n".join("    " + c(line, 300) for line in shown[:DIFF_LINES]))
        print(f"    ... {len(shown) - DIFF_LINES} more lines" if len(shown) > DIFF_LINES else "", end="")
    else:
        print("  diff:     none (a lead or a notice; nothing to apply)")


def _key(ask: Callable[[str], str]) -> str:
    for _ in range(TRIES):
        key = KEYS.get(ask("> ").strip().lower())
        if key:
            return key
    return "skip"


def _note(ask: Callable[[str], str]) -> str:
    while True:                                                          # a dismissal needs a note: asked again until there is one
        note = store.clean(ask("dismiss note (required): "), store.NOTE_MAX).strip()
        if note:
            return note
        print("error: a dismissal needs a note")


def queue(cfg: Config, limit: int, ask: Callable[[str], str], need_tty: Callable[[str], bool]) -> int:
    if limit < 1:
        print("error: --limit must be at least 1", file=sys.stderr)
        return 2
    if not need_tty("watch queue"):
        return 2
    wd = store.watch_dir(cfg)
    if store.disabled(wd):
        print("watch: disabled")
        return 0
    items = sorted((p for p, s in store.statuses(wd, now_iso()) if s == "open"), key=lambda p: (str(p["created"]), p["id"]))[:limit]
    if not items:
        print("queue empty")
        return 0
    done = {"accepted": 0, "dismissed": 0, "later": 0}
    for n, p in enumerate(items, 1):
        _card(p, n, len(items))
        try:
            key = _key(ask)
            if key == "quit":
                break
            if key == "skip":
                continue
            note = _note(ask) if key == "dismissed" else ""
        except EOFError:                                                 # the terminal went away: stop like q
            break
        store.append_decision(wd, p["id"], key, note, now_iso())
        done[key] += 1
    lock = fsio.lock(wd, blocking=True)                                  # not while a scan is promoting or writing
    try:
        store.rebalance(wd, now_iso())                                   # a freed slot opens the next queued proposal
    finally:
        os.close(lock)
    print(f"accepted {done['accepted']}, dismissed {done['dismissed']}, later {done['later']} (nothing was applied)")
    return 0


def run(cfg: Config, args, ask: Callable[[str], str], need_tty: Callable[[str], bool]) -> int:
    """Entry of `compile watch`: exit 0 (a scan always exits 0), 2 for a configuration error, a missing terminal or a bad `--limit`."""
    if args.watch_cmd == "status":
        print("\n".join(("proposals", *summary.block(summary.fields(cfg), now_iso(), status_mod.age))))
        return 0
    if args.watch_cmd == "queue":
        return queue(cfg, args.limit, ask, need_tty)
    from . import scan                                                   # lazy: scan loads the network-using modules
    try:
        lines = scan.run(cfg, args.tier, args.dry_run, args.force)
    except scan.ConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print("\n".join(lines))
    return 0
